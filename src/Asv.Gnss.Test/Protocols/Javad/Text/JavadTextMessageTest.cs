    private static IProtocolMessageFactory<JavadMessageBase, string> CreateFactory()
    {
        var builder = new ProtocolMessageFactoryBuilder<JavadMessageBase, string>(
            JavadProtocol.Info
        );
        JavadTextMessageFactory.Register(builder);
        return builder.Build();
    }

    private static JavadMessageBase Decode(
        string id,
        byte[] frame,
        JavadByteOrder order = JavadByteOrder.LittleEndian
    )
    {
        var message = CreateFactory().Create(id)!;
        message.ByteOrder = order;
        ReadOnlySpan<byte> source = frame;
        message.Deserialize(ref source);
        Assert.True(source.IsEmpty);
        return message;
    }

    private static byte[] Serialize(JavadMessageBase message)
    {
        var bytes = new byte[message.GetByteSize()];
        var destination = bytes.AsSpan();
        message.Serialize(ref destination);
        Assert.True(destination.IsEmpty);
        return bytes;
    }

    private static byte[] Frame(
        string id,
        string payload,
        JavadChecksumKind kind = JavadChecksumKind.AsciiHex8
    ) => Frame(id, Encoding.ASCII.GetBytes(payload), kind);

    // Independent literal implementation of Appendix A.1; golden vectors above also anchor this algorithm.
    private static byte[] Frame(string id, byte[] payload, JavadChecksumKind kind)
    {
        var checksumSize =
            kind == JavadChecksumKind.None ? 0
            : kind == JavadChecksumKind.AsciiHex8 ? 2
            : 1;
        var header = Encoding.ASCII.GetBytes(
            id + (payload.Length + checksumSize).ToString("X3", CultureInfo.InvariantCulture)
        );
        var frame = new byte[header.Length + payload.Length + checksumSize];
        header.CopyTo(frame, 0);
        payload.CopyTo(frame, header.Length);
        byte checksum = 0;
        foreach (var value in frame.AsSpan(0, header.Length + payload.Length))
            checksum = (byte)((((checksum << 2) | (checksum >> 6)) & 255) ^ value);
        checksum = (byte)(((checksum << 2) | (checksum >> 6)) & 255);
        if (kind == JavadChecksumKind.Binary8)
            frame[^1] = checksum;
        else if (kind == JavadChecksumKind.AsciiHex8)
            Encoding.ASCII.GetBytes(
                checksum.ToString("X2", CultureInfo.InvariantCulture),
                frame.AsSpan(frame.Length - 2)
            );
        return frame;
    }
}
