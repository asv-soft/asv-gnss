#!/usr/bin/env python3
"""Generate X20 HPG 2.11 UBX wire models from the pinned manufacturer JSON.

No network or third-party Python packages are needed. Use --check in validation.
All integer properties retain their native wire values; scales are metadata.
"""
from pathlib import Path
import argparse
import html
import json
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'Schema/u-blox-X20-HPG-2.11.json'
SCHEMA = json.loads(SOURCE.read_text())['messages']['UBX']
TYPES = {'U1': ('byte', 'UInt8', 1), 'I1': ('sbyte', 'Int8', 1),
         'U2': ('ushort', 'UInt16', 2), 'I2': ('short', 'Int16', 2),
         'U4': ('uint', 'UInt32', 4), 'I4': ('int', 'Int32', 4),
         'X1': ('byte', 'UInt8', 1), 'X2': ('ushort', 'UInt16', 2),
         'X4': ('uint', 'UInt32', 4), 'R4': ('float', 'Float', 4),
         'R8': ('double', 'Double', 8), 'CH': ('byte', 'UInt8', 1)}
HEADER = ['// <auto-generated />', '// Source: Schema/u-blox-X20-HPG-2.11.json; regenerate with Schema/generate_ubx_x20.py.', '#nullable enable', 'using System;', 'using System.Collections.Generic;', 'using Asv.IO;', '', 'namespace Asv.Gnss;', '']


def literal(value):
    return json.dumps(value, ensure_ascii=False)


def pascal(value):
    return ''.join(p[0].upper() + p[1:] for p in re.split(r'[^A-Za-z0-9]', value) if p)


def title(value):
    return ''.join(p.title() for p in re.split(r'[^A-Za-z0-9]', value) if p)


def backing(name):
    return '_' + name[0].lower() + name[1:]


def description(field):
    value = field.get('detailedDescription', 'Reserved wire field.' if field.get('reserved') else 'Native UBX wire field.')
    if field.get('scale'):
        value += ' Native wire value; multiply by ' + field['scale'] + ' to obtain ' + field.get('unit', 'the physical value') + '.'
    elif field.get('unit', '').strip():
        value += ' Unit: ' + field['unit'] + '.'
    if field['type'] == 'CH':
        value += ' ASCII bytes are preserved, including padding and bytes outside ASCII.'
    return value


def default(field):
    if field['name'].lower() not in ('version', 'msgver', 'type', 'cmd', 'command'):
        return None
    text = field.get('detailedDescription', '')
    match = re.search(r'\((0x[0-9a-fA-F]+) for (?:this|Short|Long)', text)
    if not match and field['name'].lower() in ('version', 'msgver', 'cmd', 'command'):
        match = re.search(r'Message [Vv]ersion \((0x[0-9a-fA-F]+)\)', text)
    if not match and field['name'].lower() in ('version', 'cmd', 'command'):
        match = re.search(r'(?:currently[, ]*|must be )\s*(0x[0-9a-fA-F]+|\d+)', text)
    return str(int(match[1], 0)) if match else None


def item_type(field):
    return TYPES[field['type']][0]


def primitive(field):
    return TYPES[field['type']][1] + 'Type'


def fixed_field(field):
    value = dict(field)
    value['name'] = pascal(field['name'])
    if field['repeat'] != 1:
        value['count'] = field['repeat']
    return value


def fields_for(message, class_name):
    result = []
    records = []
    for group in message['groups']:
        assert sum(f['size'] * f['repeat'] for f in group['fields']) == group['size']
        offset = 0
        for wire_field in group['fields']:
            assert wire_field['offset'] == offset, (class_name, wire_field['name'])
            offset += wire_field['size'] * wire_field['repeat']
        if group['repeat'] == 'once':
            result.extend(fixed_field(f) for f in group['fields'])
            continue
        # Flatten homogeneous groups, retaining each manufacturer's field name.
        if group['repeat'] != 'optional' and len(group['fields']) == 1 and group['fields'][0]['repeat'] == 1:
            field = fixed_field(group['fields'][0])
            field['count'] = 'variable'
            field['group'] = group
            if 'maximum' in group:
                field['maximum'] = group['maximum']
        else:
            record_name = class_name + pascal(group['name']) + 'Record'
            record_fields = [fixed_field(f) for f in group['fields']]
            records.append((record_name, record_fields, group['size']))
            field = {'name': pascal(group['name']), 'type': record_name, 'record': True,
                     'size': group['size'], 'repeat': 1, 'group': group,
                     'detailedDescription': 'UBX ' + group['name'] + ' payload group.'}
            if group['repeat'] == 'optional':
                field['optional'] = True
            else:
                field['count'] = 'variable'
        if 'maximum' in group:
            field['maximum'] = group['maximum']
        result.append(field)
    names = [f['name'] for f in result]
    assert len(names) == len(set(names)), (class_name, names)
    counts = {pascal(f['group']['field']): f['name'] for f in result
              if f.get('group', {}).get('repeat') == 'by_field'}
    for field in result:
        if field['name'] in counts:
            field['derived'] = counts[field['name']]
        group = field.get('group', {})
        if group.get('repeat') == 'by_field' and pascal(group['field']) not in names:
            matches = [(container, bit) for container in result for bit in container.get('bits', []) if bit['name'] == group['field']]
            assert len(matches) == 1, (class_name, group['field'])
            container, bit = matches[0]
            field['packedCount'] = {'property': container['name'] + pascal(bit['name']), 'maximum': (1 << bit['num']) - 1}
            field['detailedDescription'] += ' Its length must match the packed ' + field['packedCount']['property'] + ' count; update both when changing the array.'
    return result, records


def cstype(field):
    value = field['type'] if field.get('record') else item_type(field)
    if 'count' in field:
        value += '[]'
    elif field.get('optional'):
        value += '?'
    return value


def metadata_type(field):
    value = field['type'] + '.StructType' if field.get('record') else primitive(field) + '.Default'
    if field.get('count') == 'variable':
        maximum = field.get('maximum', field.get('packedCount', {}).get('maximum', 65535 // field['size']))
        return f'new ListType({value}, 0, {maximum})'
    if 'count' in field:
        return f'new ArrayType({value}, {field["count"]})'
    if field.get('optional'):
        return f'new OptionalStructType({value})'
    return value


def emit_properties(fields):
    lines = []
    for field in fields:
        name = field['name']
        member = backing(name)
        desc = description(field) if not field.get('record') else field['detailedDescription']
        if field.get('derived'):
            desc += ' Read-only count derived from ' + field['derived'] + '; edit the array instead.'
            lines.extend(['    /// <summary>' + html.escape(desc, quote=False) + '</summary>',
                          f'    public {cstype(field)} {name} => checked(({cstype(field)}){field["derived"]}.Length);'])
            continue
        initializer = None
        if 'count' in field:
            initializer = '[]' if field['count'] == 'variable' else f'new {item_type(field)}[{field["count"]}]'
        elif not field.get('record'):
            initializer = default(field)
        lines.extend([f'    private {cstype(field)} {member}' + (f' = {initializer}' if initializer else '') + ';',
                      '    /// <summary>' + html.escape(desc, quote=False) + '</summary>',
                      f'    public {cstype(field)} {name} {{ get => {member}; set => {member} = value; }}'])
        if not field.get('record') and field['type'] == 'CH' and 'count' in field:
            lines.extend(['    /// <summary>ASCII view, stopping at the first NUL; the raw byte array remains authoritative.</summary>',
                          f'    public string {name}Ascii => UbxX20Payload.Ascii({member});'])
        if not field.get('record') and 'count' not in field:
            for bit in field.get('bits', []):
                bit_name = name + pascal(bit['name'])
                mask = bit['mask']
                shift = bit['shift']
                if bit.get('type') == 'signed':
                    getter = f'({item_type(field)})((int)({name} << {32 - shift - bit["num"]}) >> {32 - bit["num"]})'
                else:
                    getter = f'({item_type(field)})(({name} & {mask}u) >> {shift})'
                lines.extend([f'    /// <summary>{html.escape(bit["name"], quote=False)} bit field (bits {shift}..{shift + bit["num"] - 1}); other bits are preserved.</summary>',
                              f'    public {item_type(field)} {bit_name}', '    {',
                              f'        get => {getter};',
                              f'        set => {name} = ({item_type(field)})(({name} & ~{mask}u) | (((uint)value << {shift}) & {mask}u));', '    }'])
    return lines


def emit_visitor(fields, message):
    lines = []
    for f in fields:
        desc = description(f) if not f.get('record') else f['detailedDescription']
        readonly = f.get('derived')
        if readonly:
            desc += ' Read-only count derived from ' + readonly + '.'
        unit = f.get('unit', '').strip()
        helper = 'UbxX20Payload.ReadOnlyField' if readonly else 'UbxVisitor.Field'
        lines.append(f'    private static readonly Field {f["name"]}Field = {helper}(nameof({f["name"]}), {metadata_type(f)}, {literal(desc)}' + (', ' + literal(unit) if unit else '') + ');')
    lines.extend(['', '    /// <summary>Cached native wire field metadata.</summary>',
                  '    public static StructType StructType { get; } = new([' + ', '.join(f['name'] + 'Field' for f in fields) + ']);',
                  '', '    /// <inheritdoc />', '    public ' + ('override ' if message else '') + 'void Accept(IVisitor visitor)', '    {',
                  '        ArgumentNullException.ThrowIfNull(visitor);'])
    for f in fields:
        name = f['name']
        member = backing(name)
        metadata = name + 'Field'
        if f.get('derived'):
            lines.extend([f'        var readOnly{name} = {name};', f'        var original{name} = readOnly{name};',
                          f'        {primitive(f)}.Accept(visitor, {metadata}, ref readOnly{name});',
                          f'        if (readOnly{name} != original{name})',
                          f'            throw new InvalidOperationException("{name} is derived from {f["derived"]} and cannot be edited directly.");'])
        elif 'count' in f:
            element = f['type'] if f.get('record') else item_type(f)
            visit = 'if (value is null) v.VisitUnknown(f, t); else Asv.IO.StructType.Accept(v, f, t, value);' if f.get('record') else f'{primitive(f)}.Accept(v, f, t, ref value);'
            create = 'new()' if f.get('record') else 'default'
            lines.extend([f'        UbxVisitor.VisitArray(visitor, {metadata}, ref {member}!, static () => {create},',
                          f'            static (IVisitor v, Field f, IFieldType t, ref {element} value) => {{ {visit} }});'])
        elif f.get('optional'):
            lines.append(f'        OptionalStructType.Accept(visitor, {metadata}, ref {member});')
        else:
            lines.append(f'        {primitive(f)}.Accept(visitor, {metadata}, ref {member});')
    lines.extend(['    }', ''])
    return lines


def read_value(f):
    return f'UbxX20Payload.Read{TYPES[f["type"]][1]}(ref buffer)'


def write_value(f, value):
    return f'UbxX20Payload.Write{TYPES[f["type"]][1]}(ref buffer, {value});'


def emit_codec(fields, message, record_size=None):
    read = []
    write = []
    size = []
    for f in fields:
        name = f['name']
        if f.get('derived'):
            read.append(f'var wire{name} = {read_value(f)};')
            write.append(write_value(f, name))
            size.extend([f'_ = {name};', f'size += {f["size"]};'])
        elif f.get('optional'):
            read.extend([f'{name} = null;', 'if (!buffer.IsEmpty)', '{', f'    UbxX20Payload.RequireAvailable(buffer.Length, 1, {f["size"]});', f'    {name} = new();', f'    {name}.Read(ref buffer);', '}'])
            write.append(f'{name}?.Write(ref buffer);')
            size.extend([f'if ({name} is not null)', '{', f'    {name}.Validate();', f'    size += {f["size"]};', '}'])
        elif 'count' in f:
            if f['count'] == 'variable':
                g = f['group']
                count = (f['packedCount']['property'] if 'packedCount' in f else f'wire{pascal(g["field"])}') if g['repeat'] == 'by_field' else f'UbxX20Payload.RemainingCount(buffer.Length, {f["size"]})'
            else:
                count = str(f['count'])
            element = f['type'] if f.get('record') else item_type(f)
            read.append(f'var count{name} = checked((int)({count}));')
            if 'maximum' in f:
                read.extend([f'if (count{name} > {f["maximum"]})', f'    throw new FormatException("{name} exceeds its maximum of {f["maximum"]} elements.");'])
            read.extend([f'UbxX20Payload.RequireAvailable(buffer.Length, count{name}, {f["size"]});',
                         f'{name} = new {element}[count{name}];', f'for (var index = 0; index < {name}.Length; index++)', '{'])
            if f.get('record'):
                read.extend([f'    {name}[index] = new();', f'    {name}[index].Read(ref buffer);'])
            else:
                read.append(f'    {name}[index] = {read_value(f)};')
            read.append('}')
            size.append(f'ArgumentNullException.ThrowIfNull({name});')
            if 'maximum' in f:
                size.extend([f'if ({name}.Length > {f["maximum"]})', f'    throw new InvalidOperationException("{name} exceeds its maximum of {f["maximum"]} elements.");'])
            if f['count'] != 'variable':
                size.extend([f'if ({name}.Length != {f["count"]})', f'    throw new InvalidOperationException("{name} must contain exactly {f["count"]} elements.");'])
            elif f['group']['repeat'] == 'by_field':
                if 'packedCount' in f:
                    prop = f['packedCount']['property']
                    size.extend([f'if ({name}.Length > {f["packedCount"]["maximum"]} || (uint){name}.Length != {prop})',
                                 f'    throw new InvalidOperationException("{name} length must equal the packed {prop} count.");'])
                else:
                    size.append(f'_ = {pascal(f["group"]["field"])};')
            size.append(f'size = checked(size + {name}.Length * {f["size"]});')
            write.extend([f'foreach (var value in {name})', '{'])
            if f.get('record'):
                size.extend([f'foreach (var value in {name})', '{', '    ArgumentNullException.ThrowIfNull(value);', '    value.Validate();', '}'])
                write.append('    value.Write(ref buffer);')
            else:
                write.append('    ' + write_value(f, 'value'))
            write.append('}')
        else:
            read.append(f'{name} = {read_value(f)};')
            write.append(write_value(f, name))
            size.append(f'size += {f["size"]};')
    if any(field.get('sumKeyLengths') for field in fields):
        common = ['var keyLength = 0;', 'foreach (var item in KeysDescription)', '    keyLength += item.KeyLengthBytes;', 'if (keyLength != Key.Length)']
        read.extend(common + ['    throw new FormatException("SPARTN key bytes do not match the declared key lengths.");'])
        size.extend(common + ['    throw new InvalidOperationException("SPARTN key bytes must match the declared key lengths.");'])
    for field in fields:
        if not field.get('record') and 'count' not in field and not field.get('derived'):
            fixed = default(field)
            if fixed is not None:
                read.extend([f'if ({field["name"]} != {fixed})',
                             f'    throw new FormatException("{field["name"]} does not identify this X20 payload variant.");'])
                size[0:0] = [f'if ({field["name"]} != {fixed})',
                             f'    throw new InvalidOperationException("{field["name"]} must be {fixed} for this X20 payload variant.");']
    if message:
        lines = ['    /// <inheritdoc />', '    protected override void ReadPayload(ref ReadOnlySpan<byte> buffer)', '    {']
    else:
        lines = ['    internal void Read(ref ReadOnlySpan<byte> buffer)', '    {']
    lines.extend('        ' + line for line in read)
    lines.extend(['    }', ''])
    lines.extend(['    /// <inheritdoc />', '    protected override void WritePayload(ref Span<byte> buffer)', '    {'] if message else ['    internal void Write(ref Span<byte> buffer)', '    {'])
    lines.extend('        ' + line for line in write)
    lines.extend(['    }', ''])
    lines.extend(['    /// <inheritdoc />', '    protected override int GetPayloadByteSize()', '    {'] if message else ['    internal int Validate()', '    {'])
    lines.append('        var size = 0;')
    lines.extend('        ' + line for line in size)
    lines.extend(['        return UbxX20Payload.CheckedSize(size);', '    }'])
    return lines



def random_value(field):
    return {'byte': '(byte)random.Next(256)', 'sbyte': 'unchecked((sbyte)random.Next(256))',
            'ushort': '(ushort)random.Next(65536)', 'short': 'unchecked((short)random.Next(65536))',
            'uint': '(uint)random.NextInt64(0, 1L << 32)', 'int': 'random.Next(int.MinValue, int.MaxValue)',
            'float': '(float)(random.NextDouble() * 200 - 100)', 'double': 'random.NextDouble() * 200 - 100'}[item_type(field)]


def emit_randomize(fields, message):
    lines = ['    /// <inheritdoc />', '    public override void Randomize(Random random)', '    {'] if message else ['    internal void Randomize(Random random)', '    {']
    lines.append('        ArgumentNullException.ThrowIfNull(random);')
    for field in fields:
        name = field['name']
        if field.get('derived') or (not field.get('record') and default(field) is not None):
            continue
        if field.get('optional'):
            lines.extend([f'        {name} = new();', f'        {name}.Randomize(random);'])
        elif 'count' in field:
            element = field['type'] if field.get('record') else item_type(field)
            count = f'random.Next(1, {min(3, field.get("maximum", 3)) + 1})' if field['count'] == 'variable' else str(field['count'])
            lines.extend([f'        {name} = new {element}[{count}];', f'        for (var index = 0; index < {name}.Length; index++)', '        {'])
            if field.get('record'):
                lines.extend([f'            {name}[index] = new();', f'            {name}[index].Randomize(random);'])
            else:
                lines.append(f'            {name}[index] = {random_value(field)};')
            lines.append('        }')
            if 'packedCount' in field:
                lines.append(f'        {field["packedCount"]["property"]} = (uint){name}.Length;')
        else:
            lines.append(f'        {name} = {random_value(field)};')
    if any(field.get('sumKeyLengths') for field in fields):
        lines.extend(['        var keyLength = 0;', '        foreach (var item in KeysDescription)', '            keyLength += item.KeyLengthBytes;',
                      '        Key = new byte[keyLength];', '        random.NextBytes(Key);'])
    return lines + ['    }', '']


def emit_record(name, fields, size):
    return ['/// <summary>Repeated or optional X20 payload record.</summary>', f'public sealed class {name} : IVisitable', '{'] + emit_properties(fields) + [''] + emit_visitor(fields, False) + emit_randomize(fields, False) + emit_codec(fields, False, size) + ['}', '']


MESSAGES = []
for class_key, group in SCHEMA.items():
    for key in group['_list']:
        m = json.loads(json.dumps(group[key]))
        # These dependent lengths are stated in field descriptions/PDF, but
        # encoded as by_size groups in the manufacturer's machine-readable JSON.
        if class_key == 'RXM' and key == 'PMP-DATA2':
            m['groups'][1].update(repeat='by_field', field='numBytesUserData', maximum=504)
        if class_key == 'RXM' and key == 'SPARTNKEY-DATA0':
            m['groups'][1]['maximum'] = 2
            m['groups'][2]['maximum'] = 510
            m['groups'][2]['fields'][0]['sumKeyLengths'] = True
        m['classId'] = group['_meta']['classId']
        m['classKey'] = class_key
        m['className'] = 'UbxX20' + title(class_key) + title(m['messageName']) + title(m['versionName'])
        MESSAGES.append(m)
assert len(MESSAGES) == 163
assert len(set(m['className'] for m in MESSAGES)) == 163


def emit_message(m):
    name = m['className']
    fields, records = fields_for(m, name)
    result = []
    for record_name, record_fields, record_size in records:
        result.extend(emit_record(record_name, record_fields, record_size))
    result.extend(['/// <summary>' + html.escape(m.get('description', 'Poll request.') + ' ' + m['label'] + ' ' + m['versionName'] + '.', quote=False) + '</summary>',
                   '/// <remarks>u-blox X20 HPG 2.11. All numbers retain their native wire scale. ' + html.escape(m.get('detailedDescription', ''), quote=False) + '</remarks>',
                   f'public sealed class {name} : UbxX20MessageBase', '{',
                   '    /// <inheritdoc />', f'    public override byte Class => 0x{m["classId"]:02X};',
                   '    /// <inheritdoc />', f'    public override byte SubClass => 0x{m["messageId"]:02X};',
                   '    /// <inheritdoc />', f'    public override string Name => {literal(m["label"])};',
                   '    /// <inheritdoc />', f'    public override string Variant => {literal(m["versionName"])};', ''])
    result.extend(emit_properties(fields))
    result.extend([''] + emit_visitor(fields, True))
    result.extend(emit_randomize(fields, True))
    result.extend(emit_codec(fields, True))
    result.extend(['}', ''])
    return result


def parse_number(value):
    return int(value, 0) if value.startswith(('0x', '-')) else int(value)


def emit_condition(node, lookup, indent='            '):
    if node.get('type') == 'static':
        found = lookup.get(node['versionName'])
        return [indent + (f'return new {found}();' if found else 'return null;')]
    check = node['check']
    offset = int(node.get('offset', 0))
    if check == 'payloadLength':
        probe = 'payload.Length'
        result = []
    else:
        assert check == 'U1', node
        result = [indent + f'if (payload.Length <= {offset}) return null;']
        probe = f'payload[{offset}]'
    cases = [case for case in node.get('cases', []) if not case.get('default')]
    defaults = [case for case in node.get('cases', []) if case.get('default')]
    for case in cases:
        values = [parse_number(value) for value in case.get('values', ['0'])]
        result.extend([indent + 'if (' + ' || '.join(f'{probe} == {value}' for value in values) + ')', indent + '{'])
        if 'condition' in case:
            result.extend(emit_condition(case['condition'], lookup, indent + '    '))
        else:
            found = lookup.get(case.get('versionName'))
            result.append(indent + '    ' + (f'return new {found}();' if found else 'return null;'))
        result.append(indent + '}')
    if defaults:
        assert len(defaults) == 1
        case = defaults[0]
        if 'condition' in case:
            result.extend(emit_condition(case['condition'], lookup, indent))
        else:
            found = lookup.get(case.get('versionName'))
            result.append(indent + (f'return new {found}();' if found else 'return null;'))
    else:
        result.append(indent + 'return null;')
    return result


def emit_factory():
    lines = HEADER + ['internal static class UbxX20GeneratedFactory', '{',
                      '    internal static IReadOnlyList<UbxX20MessageDescriptor> Messages { get; } = Array.AsReadOnly(new UbxX20MessageDescriptor[]', '    {']
    for m in MESSAGES:
        name = m['className']
        lines.append(f'        new(0x{m["classId"]:02X}{m["messageId"]:02X}, {literal(m["label"])}, {literal(m["versionName"])}, {literal(m["type"])}, typeof({name}), static () => new {name}()),')
    lines.extend(['    });', '', '    internal static UbxX20MessageBase? Create(ushort id, ReadOnlySpan<byte> payload)', '    {',
                  '        switch (id)', '        {'])
    ids = {}
    for m in MESSAGES:
        ids.setdefault((m['classKey'], m['messageName'], m['classId'], m['messageId']), []).append(m)
    for (class_key, message_key, class_id, message_id), variants in ids.items():
        lines.extend([f'            case 0x{class_id:02X}{message_id:02X}:', '            {'])
        classifier = SCHEMA[class_key]['_meta']['classifiers'].get(message_key)
        # Published JSON errata: the empty SOS poll is absent from its U1 classifier.
        if class_key == 'UPD' and message_key == 'SOS':
            lines.append('                if (payload.IsEmpty) return new UbxX20UpdSosPoll0();')
        # Published JSON errata: the 8-byte PMREQ leaf omits its variant name.
        if class_key == 'RXM' and message_key == 'PMREQ':
            classifier = json.loads(json.dumps(classifier))
            classifier['cases'][0]['versionName'] = '0'
        if classifier:
            lines.extend(emit_condition(classifier, {m['versionName']: m['className'] for m in variants}, '                '))
        else:
            assert len(variants) == 1
            lines.append(f'                return new {variants[0]["className"]}();')
        lines.append('            }')
    lines.extend(['            default: return null;', '        }', '    }', '',
                  '    internal static UbxX20MessageBase? CreateDefault(ushort id)', '    {', '        return id switch', '        {'])
    for (_, _, class_id, message_id), variants in ids.items():
        default_variant = next((m for m in variants if m['versionName'].startswith('DATA')), variants[0])
        lines.append(f'            0x{class_id:02X}{message_id:02X} => new {default_variant["className"]}(),')
    lines.extend(['            _ => null,', '        };', '    }', '',
                  '    internal static void RegisterMissing(IProtocolMessageFactoryBuilder<UbxMessageBase, ushort> builder, ISet<ushort> registeredIds)', '    {'])
    for (_, _, class_id, message_id), variants in ids.items():
        default_variant = next((m for m in variants if m['versionName'].startswith('DATA')), variants[0])
        lines.extend([f'        if (registeredIds.Add(0x{class_id:02X}{message_id:02X}))',
                      f'            builder.Add<{default_variant["className"]}>();'])
    lines.extend(['    }', '}', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = {ROOT / 'Generated/UbxX20GeneratedFactory.g.cs': emit_factory()}
    for cls in SCHEMA:
        lines = HEADER.copy()
        for message in MESSAGES:
            if message['classKey'] == cls:
                lines.extend(emit_message(message))
        files[ROOT / ('Generated/UbxX20' + title(cls) + 'Messages.g.cs')] = '\n'.join(lines)
    stale = []
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, 'Generated X20 models are stale:\n' + '\n'.join(stale) + '\n')
    print(('Verified' if args.check else 'Generated') + f' {len(MESSAGES)} UBX X20 variants in {len(files)} files.')


if __name__ == '__main__':
    main()
