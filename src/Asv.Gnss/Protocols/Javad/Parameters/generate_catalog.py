#!/usr/bin/env python3
"""Generate GREIS object metadata from pdftotext -layout GREIS-4.2.01.pdf output.

The supplied PDF is authoritative. This extracts declarations, not executable
validation rules: supported objects and ranges can depend on receiver firmware.
Usage: python3 generate_catalog.py /path/to/greis-layout.txt
"""
import json
import pathlib
import re
import sys


def extract(source):
    declarations = []
    for page in source.split("\f"):
        footer = re.search(r"GREIS\s+www\.javad\.com\s+(\d+)\s*$", page)
        if not footer or int(footer[1]) < 190:
            continue
        number = int(footer[1])
        # The source repeats 'Name:' in five declarations. On p514 the
        # access field for sid/out/first is accidentally labelled 'Name:'.
        for label in ("Name", "Access", "Type", "Values", "Default", "Options"):
            page = re.sub(label + r":\s*" + label + ":", label + ":", page)
        page = re.sub(r"(?m)^(\s*)Name:\s+(rw)\s*$", r"\1Access: \2", page)
        matches = list(re.finditer(r"(?m)^\s*Name:\s*(/[^\n]+)", page))
        for index, match in enumerate(matches):
            declaration = match[1].strip()
            path = re.match(r"/[^\s,]+", declaration)[0]
            block = page[match.end():matches[index + 1].start() if index + 1 < len(matches) else len(page)]
            fields = {}
            for field in ("Access", "Type", "Values", "Default", "Options"):
                found = re.search(r"(?m)^([ \t]*)" + field + r":[ \t]*([^\n]+)", block)
                value = found[2].strip() if found else ""
                if found:
                    # Wrapped metadata is indented beyond the field label.
                    for continuation in block[found.end():].splitlines()[1:]:
                        if not continuation.strip() or len(continuation) - len(continuation.lstrip()) <= len(found[1]):
                            break
                        value += " " + continuation.strip()
                fields[field] = value
            declarations.append((path, declaration, fields["Access"], fields["Type"], fields["Values"], fields["Default"], fields["Options"], number))
    return declarations


def generate(rows):
    lines = ["// <auto-generated />", "// Source: GREIS-4.2.01.pdf, object declarations including appendix B.", "// Regenerate with Parameters/generate_catalog.py and pdftotext -layout output.", "using System.Collections.Immutable;", "", "namespace Asv.Gnss;", "", "public static partial class JavadParameterCatalog", "{", "    private static ImmutableArray<JavadParameterDescriptor> Create()", "    {", "        var values = ImmutableArray.CreateBuilder<JavadParameterDescriptor>();"]
    for chunk in range((len(rows) + 99) // 100):
        lines.append(f"        values.AddRange(Part{chunk}());")
    lines.extend(["        return values.ToImmutable();", "    }"])
    for chunk in range((len(rows) + 99) // 100):
        lines.extend(["", f"    private static JavadParameterDescriptor[] Part{chunk}() =>", "    ["])
        for row in rows[chunk * 100:(chunk + 1) * 100]:
            lines.append("        new(" + ", ".join(json.dumps(value, ensure_ascii=False) for value in row) + "),")
        lines.append("    ];")
    lines.extend(["}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    rows = extract(pathlib.Path(sys.argv[1]).read_text())
    output = pathlib.Path(__file__).with_name("JavadParameterCatalog.Generated.cs")
    output.write_text(generate(rows))
    print(f"Generated {len(rows)} GREIS object declarations in {output.name}")
